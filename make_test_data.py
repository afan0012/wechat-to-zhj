def write_xls(path, header, rows):
    wb = xlwt.Workbook(encoding="utf-8")
    ws = wb.add_sheet("Sheet1")
    for c, h in enumerate(header):
        ws.write(0, c, h)
    for r, row in enumerate(rows, 1):
        for c, v in enumerate(row):
            if v is not None and v != "":
                ws.write(r, c, v)
    wb.add_sheet("Sheet2")
    wb.add_sheet("Sheet3")
    wb.save(str(path))


